"""Explicit, bounded replay of one archived candidate. Launches a billable H200 job."""
import hashlib
import json
import pathlib
import time

from modal_runner_device import app, experiment

ROOT = pathlib.Path(__file__).resolve().parent.parent

@app.local_entrypoint()
def replay(record: str, problem_dir: str, candidate: str, budget_usd: float, repeats: int = 20):
    if repeats < 2 or repeats > 100 or repeats % 2:
        raise ValueError('Use an even repeat count between 2 and 100')
    if budget_usd < 3:
        raise ValueError('This single-run wrapper requires a $3 conservative reservation')
    record_path = pathlib.Path(record)
    data = json.loads(record_path.read_text())
    ref = data.get('source_files', {}).get(candidate)
    if ref is None:
        raise ValueError('No source snapshot for that candidate; inspect record source_files')
    source = (ROOT / ref['path']).read_bytes()
    if hashlib.sha256(source).hexdigest() != ref['sha256']:
        raise ValueError('Archived source checksum mismatch')
    official = pathlib.Path(problem_dir)
    files = {p.name: p.read_text() for p in official.glob('*.py') if p.name != 'submission.py'}
    if not {'reference.py', 'baseline.py', 'checks.py'} <= files.keys():
        raise ValueError('Supply a directory generated by okc init for the matching problem')
    def unique(rows):
        result = []
        for row in rows:
            if row not in result:
                result.append(row)
        return result
    cases = unique([x['case'] for x in data['timings'] if x['candidate'] == candidate])
    if not cases:
        raise ValueError('Candidate has no archived timing cases; it may have failed validation')
    extras = unique([x['case'] for x in data.get('validation', [])
                     if x.get('candidate') == candidate and x['case'] not in cases
                     and 'phase' not in x['case']])
    out_dir = ROOT / 'results' / 'replays'
    out_dir.mkdir(parents=True, exist_ok=True)
    ledger_path = out_dir / 'budget.json'
    ledger = json.loads(ledger_path.read_text()) if ledger_path.exists() else {'reservations': []}
    # Serial use only. Do not run concurrent wrappers against the same ledger.
    spent = sum(x['reserved_usd'] for x in ledger['reservations'])
    if spent + 3 > budget_usd:
        raise ValueError('Cumulative local replay reservations would exceed the supplied cap')
    stamp = str(time.time_ns())
    ledger['reservations'].append({'id': stamp, 'reserved_usd': 3, 'candidate': candidate})
    ledger_path.write_text(json.dumps(ledger, indent=2))
    result = json.loads(experiment.remote(files, {candidate: source.decode()}, cases, extras, repeats))
    result.update(problem=data.get('problem'), source_files={candidate: ref},
                  replay_of=str(record_path), historical_environment_reproduced=False)
    target = out_dir / (stamp + '.json')
    target.write_text(json.dumps(result, indent=2))
    print('Saved', target)
